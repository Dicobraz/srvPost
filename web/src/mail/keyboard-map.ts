/*
  Транслитерация раскладки (WEB-05): запрос, набранный в EN-раскладке на русской раскладке
  клавиатуры, пробуется вторым вариантом — посимвольно по карте qwerty→йцукен (практику Postman:
  «rdfhnfk» → «квартал»). Серверную логику не трогаем: вариант объединяется с исходным запросом
  через OR в одном Email/query (search.ts) — один поход в сеть, сниппеты считаются сразу для обоих
  вариантов, а выдача остаётся единой (отсортированной по дате). Решение против «второго прохода»
  (повторного запроса, когда первый дал мало результатов): без второго запроса нет скачка списка
  и гонки с debounce; OR не искажает морфологию — каждый вариант анализируется сервером отдельно.
*/

/** Карта нижнего регистра qwerty → йцукен (стандартная раскладка Windows/«Русская»). */
const QWERTY_TO_JCUKEN: Record<string, string> = {
  q: "й", w: "ц", e: "у", r: "к", t: "е", y: "н", u: "г", i: "ш", o: "щ", p: "з",
  "[": "х", "]": "ъ", a: "ф", s: "ы", d: "в", f: "а", g: "п", h: "р", j: "о",
  k: "л", l: "д", ";": "ж", "'": "э", z: "я", x: "ч", c: "с", v: "м", b: "и",
  n: "т", m: "ь", ",": "б", ".": "ю", "`": "ё",
};

/**
 * Вариант запроса в правильной раскладке: посимвольный перевод qwerty→йцукен.
 * Возвращает null, если перевод не нужен или невозможен:
 *  - текст уже содержит кириллицу (значит раскладка та) или латиницу вне карты;
 *  - перевод не меняет текст (нет букв вовсе — цифры и знаки остаются как были).
 * Цифры и знаки препинания проходят без изменений (на обеих раскладках цифровой ряд совпадает).
 */
export function layoutVariant(text: string): string | null {
  let changed = false;
  let out = "";
  for (const ch of text) {
    const lower = ch.toLowerCase();
    const mapped = QWERTY_TO_JCUKEN[lower];
    if (mapped) {
      out += ch === lower ? mapped : mapped.toUpperCase();
      changed = true;
      continue;
    }
    // Буква вне карты (кириллица, латиница с диакритикой) — раскладка не та или смешанный
    // ввод: частичный перевод исказил бы запрос, вариант не строим. Цифры и знаки — проходят.
    if (/\p{L}/u.test(ch)) return null;
    out += ch;
  }
  return changed && out !== text ? out : null;
}

/**
 * Варианты текстового условия для сервера: исходный запрос и, если пользователь печатал в чужой
 * раскладке, перевод qwerty→йцукен (их объединяет search.ts через OR). Порядок — исходный первым:
 * сниппеты подсвечивают совпадения обоих вариантов одинаково.
 */
export function textVariants(text: string, enabled: boolean): string[] {
  const trimmed = text.trim();
  if (!trimmed) return [];
  const variant = enabled ? layoutVariant(trimmed) : null;
  return variant ? [trimmed, variant] : [trimmed];
}
